export class RavenDomainError extends Error {
  readonly code: RavenErrorCode;
  readonly details?: Record<string, unknown>;

  constructor(
    code: RavenErrorCode,
    message: string,
    details?: Record<string, unknown>,
  ) {
    super(message);
    this.name = "RavenDomainError";
    this.code = code;
    this.details = details;
  }
}
